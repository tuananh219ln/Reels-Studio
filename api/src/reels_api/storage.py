"""File storage behind one small interface, so a later R2 backend only replaces this module's backend.

Keys are always generated by the server (e.g. `videos/12/scene-ab12.jpg`); a key never comes from a client.
"""

import os
import re
import shutil
import tempfile
from pathlib import Path

from . import config

_KEY = re.compile(r"[a-z0-9][a-z0-9_.-]*(/[a-z0-9][a-z0-9_.-]*)*")


class StorageError(Exception):
    pass


class DirectoryStorage:
    def __init__(self, root: Path):
        self.root = Path(root)

    def path(self, key: str) -> Path:
        """Local file for reading (Pillow, FFmpeg, FileResponse); it may not exist."""
        if not _KEY.fullmatch(key) or ".." in key:
            raise StorageError(f"invalid storage key: {key!r}")
        return self.root / key

    def exists(self, key: str) -> bool:
        return self.path(key).is_file()

    def save_bytes(self, key: str, data: bytes) -> None:
        self._write(key, lambda handle: handle.write(data))

    def save_file(self, key: str, source: Path) -> None:
        with open(source, "rb") as file:
            self._write(key, lambda handle: shutil.copyfileobj(file, handle))

    def copy_to(self, key: str, target: Path) -> Path:
        shutil.copyfile(self.path(key), target)
        return target

    def delete(self, key: str | None) -> None:
        if key:
            self.path(key).unlink(missing_ok=True)

    def delete_prefix(self, prefix: str) -> None:
        shutil.rmtree(self.path(prefix.rstrip("/")), ignore_errors=True)

    def _write(self, key: str, write) -> None:
        # Readers never see a half-written file: write beside the target, then replace it atomically.
        target = self.path(key)
        target.parent.mkdir(parents=True, exist_ok=True)
        handle, temp = tempfile.mkstemp(prefix=".", suffix=".tmp", dir=target.parent)
        try:
            with os.fdopen(handle, "wb") as file:
                write(file)
            os.replace(temp, target)
        except BaseException:
            Path(temp).unlink(missing_ok=True)
            raise


def get_storage() -> DirectoryStorage:
    return DirectoryStorage(config.storage_dir())
